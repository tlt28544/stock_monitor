class ReadableFrame(KeepInFrame):
    def wrap(self, width, height):
        result = super().wrap(width,height)
        if getattr(self,'_scale',1) > 1.15:
            raise DataQualityError('Report content exceeds two-page readable layout; shorten synthesis or simplify valuation rows')
        return result


def atomic_write(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True,exist_ok=True)
    fd, name = tempfile.mkstemp(prefix='.'+path.name+'.',dir=path.parent)
    try:
        with os.fdopen(fd,'wb') as f:
            f.write(data.encode() if isinstance(data,str) else data)
            f.flush()
            os.fsync(f.fileno())
        os.replace(name,path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def valuation_rows(v):
    rows = [['Business / Adjustment','Fundamental Driver','Valuation Driver','Implied Segment Value']]
    for row in v['rows']:
        rows.append([row['name'],row['fundamental'],row['driver'],display(Decimal(row['value']))+'m' if row['value'] is not None else 'N/A'])
    rows.extend([
        ['Total Equity Value', '', v['currency']+' millions', display(Decimal(v['equity_value'])) if v['equity_value'] is not None else 'N/A'],
        ['Implied Price per Share','','', display(Decimal(v['implied_price'])) if v['implied_price'] is not None else 'N/A'],
        ['Upside/Downside','','',display(Decimal(v['upside']))+'%' if v['upside'] is not None else 'N/A'],
        ['Valuation As-of Date','','',v['as_of']]])
    return rows


def render(destination, ticker, date, version, events, research, valuation, warnings, demo=False):
    """Exactly two pages or fail validation. No successful output is published on layout failure."""
    destination = Path(destination)
    destination.mkdir(parents=True,exist_ok=True)
    styles = getSampleStyleSheet()
    for name in styles.byName:
        styles[name].fontName = 'ResearchBold' if name in ('Title','Heading1','Heading2') else 'Research'
    styles.add(ParagraphStyle(name='Compact',fontName='Research',fontSize=8.2,leading=10.5,spaceAfter=4))
    styles.add(ParagraphStyle(name='Tiny',fontName='Research',fontSize=6.8,leading=8.1,spaceAfter=2))
    styles['Heading2'].fontSize=11
    styles['Heading2'].leading=13
    styles['Heading2'].spaceBefore=7
    styles['Heading2'].spaceAfter=4
    story, md = [], []
    index = {e['id']:i+1 for i,e in enumerate(events)}
    def p(text, style='Compact', raw=False):
        return Paragraph(text if raw else escape(text),styles[style])
    def heading(text):
        story.append(p(text,'Heading2'))
        md.append('\n## '+text+'\n')
    def findings(name, values):
        heading(name)
        for f in values:
            refs = ' '.join(f'[{index[r]}]' for r in f.event_ids)
            story.append(p(f.text+' '+refs))
            md.append('- '+f.text+' '+refs)
    label = 'SYNTHETIC DEMO - NOT INVESTMENT RESEARCH' if demo else 'Weekly Equity Research'
    title = f'{ticker} | {label} | {date}'
    story.append(p(title,'Title'))
    md.append('# '+title+'\n')
    meta = f'Trailing 90 calendar days | Version {version} | Facts from sources; interpretations generated by model'
    story.append(p(meta,'Tiny')); md.append(meta)
    coverage = 'Coverage: ' + ('; '.join(warnings) if warnings else 'Provider window ingested; provider coverage limitations apply')
    if len(coverage)>650:
        raise DataQualityError('Coverage disclosures exceed report layout; review data quality')
    story.append(p(coverage,'Tiny')); md.append(coverage)
    findings('Executive Summary',research.executive_summary)
    heading('Major Developments - Source Facts')
    for e in events[:4]:
        text = f"[{index[e['id']]}] {e['date']} | {e['title'][:160]} - Source excerpt: {e['summary'][:160]}"
        story.append(p(text)); md.append('- '+text)
    heading('Sources')
    for e in events:
        # Cite all sources, including duplicates, so the persisted event can be audited.
        for s in e['sources'][:2]:
            text = f"[{index[e['id']]}] {e['date']} {s['provider']}: {e['title'][:85]}"
            link = f'<link href={quoteattr(s["url"])} color="blue">{escape(text)}</link>'
            story.append(p(link,'Tiny',raw=True))
            md.append(f'- [{text}]({s["url"]})')
    story.append(PageBreak())
    findings('Investment Implications - Model Interpretation',research.investment_implications)
    findings('What to Watch Next',research.what_to_watch)
    findings('Valuation Assumptions to Review - No Automatic Changes',research.valuation_review)
    if valuation.get('news_review_flags'):
        text = 'Material news review flags (assumptions unchanged): ' + '; '.join(f"[{index[f['event_id']]}] {f['category']}" for f in valuation['news_review_flags'])
        story.append(p(text,'Tiny')); md.append(text)
    if valuation['warnings']:
        text = 'Valuation limitations: '+'; '.join(valuation['warnings'])
        story.append(p(text[:1500],'Tiny')); md.append('\n'+text)
    # Detailed analyst rationale and provenance are in the companion JSON, leaving the table concise.
    provenance = (f"Analyst reference revision: {valuation['revision'] or 'N/A'} | Input as-of: {valuation['input_as_of'] or 'N/A'} | "
                  f"Current price: {valuation.get('current_share_price') or 'N/A'} | Price timestamp: {valuation.get('price_timestamp') or 'N/A'}")
    story.append(p(provenance,'Tiny')); md.append(provenance)
    notes = (valuation.get('coverage_notes','')+' '+valuation.get('adjustment_notes','')).strip()
    if notes:
        story.append(p(notes[:650],'Tiny')); md.append(notes)
    heading('Valuation Table')
    rows = valuation_rows(valuation)
    cells = [[p(cell,'Tiny') for cell in row] for row in rows]
    table = Table(cells,colWidths=[120,135,135,114],repeatRows=1)
    table.setStyle(TableStyle([
        ('BACKGROUND',(0,0),(-1,0),colors.HexColor('#e4eaf2')),
        ('VALIGN',(0,0),(-1,-1),'TOP'),('GRID',(0,0),(-1,-1),.35,colors.HexColor('#bdc5cf')),
        ('LEFTPADDING',(0,0),(-1,-1),4),('RIGHTPADDING',(0,0),(-1,-1),4),
        ('TOPPADDING',(0,0),(-1,-1),4),('BOTTOMPADDING',(0,0),(-1,-1),4)]))
    story.append(table)
    md.append('| '+' | '.join(rows[0])+' |\n|'+ '|'.join(['---']*4)+'|')
    md.extend('| '+' | '.join(row)+' |' for row in rows[1:])
    fd, temporary = tempfile.mkstemp(suffix='.pdf',prefix=f'.{ticker}.',dir=destination)
    os.close(fd)
    try:
        doc = SimpleDocTemplate(temporary,pagesize=(612,792),rightMargin=54,leftMargin=54,topMargin=35,bottomMargin=35,
                                title=title,author='Equity Research Pipeline')
        def footer(canvas, document):
            canvas.saveState(); canvas.setFont('Research',7)
            canvas.drawString(54,20,f'{ticker} | {date} | {version} | Page {document.page}')
            canvas.restoreState()
        split = next(i for i,f in enumerate(story) if isinstance(f,PageBreak))
        pages = [ReadableFrame(504,700,story[:split],mode='shrink'), PageBreak(), ReadableFrame(504,700,story[split+1:],mode='shrink')]
        doc.build(pages,onFirstPage=footer,onLaterPages=footer)
        validate_pdf(temporary,ticker,events)
        # MD and JSON accompany the exact same report. Job completion follows all writes and checks.
        atomic_write(destination/f'{ticker}.md','\n'.join(md)+'\n')
        atomic_write(destination/f'{ticker}.json',json.dumps({'ticker':ticker,'date':date,'version':version,'demo':demo,
                    'research':research.model_dump(),'events':events,'valuation':valuation,'coverage_warnings':warnings},indent=2))
        os.replace(temporary,destination/f'{ticker}.pdf')
    finally:
        if os.path.exists(temporary): os.unlink(temporary)
    return {ext: {'path':str((destination/f'{ticker}.{ext}').resolve()),'sha256':digest(destination/f'{ticker}.{ext}')}
            for ext in ('pdf','md','json')}


def validate_pdf(path,ticker,events):
    try:
        reader = PdfReader(path)
        if len(reader.pages)!=2:
            raise DataQualityError(f'PDF must have two pages; rendered {len(reader.pages)}')
        first, last = [page.extract_text() or '' for page in reader.pages]
        if ticker not in first or 'Executive Summary' not in first or 'Valuation Table' not in last:
            raise DataQualityError('PDF is missing required content')
        if 'Total Equity Value' not in last or 'Valuation As-of Date' not in last:
            raise DataQualityError('PDF is missing valuation totals')
        urls = {str(annotation.get_object().get('/A',{}).get('/URI','')) for page in reader.pages for annotation in page.get('/Annots',[])}
        required = {s['url'] for e in events for s in e['sources'][:2]}
        if not required <= urls:
            raise DataQualityError('PDF source links missing')
    except DataQualityError:
        raise
    except Exception as exc:
        raise DataQualityError('Unreadable PDF: '+type(exc).__name__) from None


def validate_artifacts(artifacts,ticker,events):
    if not artifacts:
        return False
    try:
        for a in artifacts.values():
            if digest(a['path']) != a['sha256']: return False
        validate_pdf(artifacts['pdf']['path'],ticker,events)
        return True
    except (OSError,ValueError,DataQualityError,KeyError):
        return False
